-- F8 · agent-mail 中继投递队列
create or replace function public.cfm_notification_pending(input jsonb)
returns jsonb
language sql
stable
set search_path = public
as $$
  select coalesce(jsonb_agg(to_jsonb(r) order by r.created_at, r.id), '[]'::jsonb)
  from (
    select * from notification_queue
    where delivered = false
    order by created_at, id
    limit least(greatest(coalesce((input->>'limit')::integer, 50), 1), 200)
  ) r;
$$;

create or replace function public.cfm_notification_queue(input jsonb)
returns jsonb
language sql
stable
set search_path = public
as $$
  select coalesce(jsonb_agg(to_jsonb(r) order by r.created_at desc, r.id desc), '[]'::jsonb)
  from (
    select * from notification_queue
    order by created_at desc, id desc
    limit least(greatest(coalesce((input->>'limit')::integer, 100), 1), 500)
  ) r;
$$;

create or replace function public.cfm_enqueue_notification(input jsonb)
returns bigint
language plpgsql
set search_path = public
as $$
declare new_id bigint;
begin
  insert into notification_queue (channel, subject, body, payload)
  values (
    case when input->>'channel' in ('telegram', 'email', 'webhook', 'agent_mail')
      then input->>'channel' else 'agent_mail' end,
    coalesce(input->>'subject', ''),
    coalesce(input->>'body', ''),
    coalesce(input->'payload', '{}'::jsonb)
  )
  returning id into new_id;
  return new_id;
end;
$$;

create or replace function public.cfm_ack_notifications(input jsonb)
returns integer
language plpgsql
set search_path = public
as $$
declare affected integer;
begin
  update notification_queue
     set delivered = true,
         delivered_at = now(),
         attempts = attempts + 1,
         last_error = null
   where delivered = false
     and id in (
       select (value)::bigint
       from jsonb_array_elements_text(coalesce(input->'ids', '[]'::jsonb)) as t(value)
       where value ~ '^[0-9]+$'
     );
  get diagnostics affected = row_count;
  return affected;
end;
$$;

-- 兜底：超过 N 小时未 ack 自动标记已投递，防止队列无限堆积（Cron 调用）。
create or replace function public.cfm_expire_notifications(input jsonb)
returns integer
language plpgsql
set search_path = public
as $$
declare
  affected integer;
  hours integer := least(greatest(coalesce((input->>'hours')::integer, 24), 1), 720);
begin
  update notification_queue
     set delivered = true, delivered_at = now(), last_error = 'timeout'
   where delivered = false
     and created_at < now() - (hours || ' hours')::interval;
  get diagnostics affected = row_count;
  return affected;
end;
$$;

