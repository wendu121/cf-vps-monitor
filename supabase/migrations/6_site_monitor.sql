-- -----------------------------------------------------------------------------
-- cf_sync_runs：资产/域名同步运行记录（F1/F3）
create table if not exists cf_sync_runs (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('assets', 'domains')),
  ran_at timestamptz not null default now(),
  new_count integer not null default 0,
  skipped_count integer not null default 0,
  error text
);
create index if not exists idx_cf_sync_runs_kind_ran on cf_sync_runs(kind, ran_at desc);

-- -----------------------------------------------------------------------------
-- cf_domains：Workers/Pages 自定义域名 + SSL 到期（F3）
create table if not exists cf_domains (
  id bigint generated by default as identity primary key,
  project_name text not null,
  project_type text not null check (project_type in ('worker', 'pages')),
  domain text not null,
  zone_id text,
  ssl_days_left integer,
  synced_at timestamptz not null default now(),
  unique (project_name, domain)
);
create index if not exists idx_cf_domains_ssl on cf_domains(ssl_days_left);
create index if not exists idx_cf_domains_synced on cf_domains(synced_at desc);

-- -----------------------------------------------------------------------------
-- notification_queue：agent-mail 中继投递队列（F8）
create table if not exists notification_queue (
  id bigint generated by default as identity primary key,
  channel text not null check (channel in ('telegram', 'email', 'webhook', 'agent_mail')),
  subject text not null,
  body text not null,
  payload jsonb,
  delivered boolean not null default false,
  delivered_at timestamptz,
  attempts integer not null default 0,
  last_error text,
  created_at timestamptz not null default now()
);
create index if not exists idx_notification_queue_pending
  on notification_queue(delivered, created_at);

