create or replace function public.cfm_cf_domains()
returns jsonb
language sql
stable
set search_path = public
as $$
  select coalesce(
    jsonb_agg(to_jsonb(row_data) order by project_type asc, project_name asc, domain asc),
    '[]'::jsonb
  )
  from (select * from cf_domains) row_data;
$$;

create or replace function public.cfm_cf_sync_runs()
returns jsonb
language sql
stable
set search_path = public
as $$
  select coalesce(
    jsonb_agg(to_jsonb(row_data) order by ran_at desc, id desc),
    '[]'::jsonb
  )
  from (select * from cf_sync_runs) row_data;
$$;

-- 单事务同步：先 upsert 输入集，再删除不在输入集内的旧行。
-- 任一步异常整体回滚，绝不会在失败时留空表（修复 clear+upsert 两次独立 RPC 的原子性缺陷）。
create or replace function public.cfm_sync_cf_domains(input_rows jsonb)
returns void
language plpgsql
set search_path = public
as $$
begin
  insert into cf_domains (project_name, project_type, domain, zone_id, ssl_days_left, synced_at)
  select
    coalesce(x->>'project_name', ''),
    case when x->>'project_type' in ('worker', 'pages') then x->>'project_type' else 'worker' end,
    coalesce(x->>'domain', ''),
    nullif(x->>'zone_id', ''),
    nullif(x->>'ssl_days_left', '')::integer,
    coalesce((x->>'synced_at')::timestamptz, now())
  from jsonb_array_elements(input_rows) as t(x)
  on conflict (project_name, domain) do update set
    project_type = excluded.project_type,
    zone_id = excluded.zone_id,
    ssl_days_left = excluded.ssl_days_left,
    synced_at = excluded.synced_at;

  delete from cf_domains
  where not exists (
    select 1 from jsonb_array_elements(input_rows) as t(x)
    where (x->>'project_name') = cf_domains.project_name
      and (x->>'domain') = cf_domains.domain
  );
end;
$$;

create or replace function public.cfm_insert_cf_sync_run(input_run jsonb)
returns bigint
language plpgsql
set search_path = public
as $$
declare
  new_id bigint;
begin
  insert into cf_sync_runs (kind, new_count, skipped_count, error)
  values (
    case when input_run->>'kind' in ('assets', 'domains') then input_run->>'kind' else 'assets' end,
    coalesce((input_run->>'new_count')::integer, 0),
    coalesce((input_run->>'skipped_count')::integer, 0),
    nullif(input_run->>'error', '')
  )
  returning id into new_id;
  return new_id;
end;
$$;

-- -----------------------------------------------------------------------------
-- F4 · SLA 月报：按站点按月聚合可用率（实时聚合，不落中间表，避免双写不一致）
-- 入参：{ month: 'YYYY-MM' }（缺省当月）。返回每站点 total/up/sla_pct/downtime_min。
create or replace function public.cfm_website_sla_report(input jsonb)
returns jsonb
language sql
stable
set search_path = public
as $$
  with bounds as (
    select
      date_trunc('month', coalesce(nullif(input->>'month', ''), to_char(now(), 'YYYY-MM'))::date) as m_start
  ),
  agg as (
    select
      wc.monitor_id,
      count(*) as total_checks,
      count(*) filter (where wc.ok) as up_checks,
      round(avg(wc.latency_ms))::integer as avg_latency_ms,
      max(wc.checked_at) as last_checked_at
    from website_checks wc, bounds b
    where wc.checked_at >= b.m_start
      and wc.checked_at < b.m_start + interval '1 month'
    group by wc.monitor_id
  )
  select coalesce(jsonb_agg(x order by x->>'name'), '[]'::jsonb)
  from (
    select jsonb_build_object(
      'monitor_id', m.id,
      'name', m.name,
      'url', m.url,
      'interval_sec', m.interval_sec,
      'total_checks', coalesce(a.total_checks, 0),
      'up_checks', coalesce(a.up_checks, 0),
      'sla_pct', case when coalesce(a.total_checks, 0) > 0
        then round((coalesce(a.up_checks, 0)::numeric / a.total_checks) * 100, 3)
        else null end,
      'downtime_min', round(
        ((coalesce(a.total_checks, 0) - coalesce(a.up_checks, 0)) * coalesce(m.interval_sec, 0)) / 60.0, 1),
      'avg_latency_ms', a.avg_latency_ms,
      'last_checked_at', a.last_checked_at
    ) as x
    from website_monitors m
    join agg a on a.monitor_id = m.id
  ) s;
$$;

-- -----------------------------------------------------------------------------
-- F6 · 多区域共识（D2-B）：按 Agent 节点（website_checks.source_client）多数表决。
-- 入参：{ monitor_id, window_minutes? }。阈值 CONSENSUS_MIN = 0.5（与 site-monitor 一致）。
create or replace function public.cfm_website_consensus(input jsonb)
returns jsonb
language sql
stable
set search_path = public
as $$
  with params as (
    select
      (input->>'monitor_id')::bigint as monitor_id,
      least(greatest(coalesce((input->>'window_minutes')::integer, 30), 1), 1440) as window_minutes
  ),
  recent as (
    select wc.*
    from website_checks wc, params p
    where wc.monitor_id = p.monitor_id
      and wc.checked_at >= now() - (p.window_minutes || ' minutes')::interval
  ),
  per_node as (
    select
      coalesce(source_client, source_type) as node,
      count(*) as checks,
      count(*) filter (where ok) as up,
      bool_or(ok) as any_up,
      round(avg(latency_ms))::integer as avg_latency_ms,
      max(checked_at) as last_checked_at,
      max(case when not ok then coalesce(effective_reason, error) end) as last_error_reason
    from recent
    group by coalesce(source_client, source_type)
  ),
  totals as (
    select count(*) as node_count, count(*) filter (where any_up) as up_nodes from per_node
  )
  select jsonb_build_object(
    'monitor_id', (select monitor_id from params),
    'window_minutes', (select window_minutes from params),
    'consensus_min', 0.5,
    'node_count', (select node_count from totals),
    'up_nodes', (select up_nodes from totals),
    'consensus_ratio', case when (select node_count from totals) > 0
      then round((select up_nodes from totals)::numeric / (select node_count from totals), 3) else null end,
    'consensus_status', case
      when (select node_count from totals) = 0 then 'unknown'
      when (select up_nodes from totals)::numeric / (select node_count from totals) >= 0.5 then 'up'
      else 'down' end,
    'nodes', coalesce((select jsonb_agg(to_jsonb(p) order by p.node) from per_node p), '[]'::jsonb)
  );
$$;

